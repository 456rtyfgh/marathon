/**
 * 같은 묶음의 다른 표기 (관련 검색어 칩용). 검색어 자신·ONE_WAY 표기는 뺀다. 없으면 [].
 * 검색어가 묶음 표기 하나와 정확히 같을 때만 (일부만 겹치면 빈 목록).
 */
export function aliasSiblings(term: string): string[] {
  const t = term.normalize('NFC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '');
  if (!t) return [];
  const out: string[] = [];
  for (const group of ALIASES) {
    if (!group.includes(t)) continue;
    for (const b of group) if (b !== t && !ONE_WAY.has(b) && !out.includes(b)) out.push(b);
  }
  return out;
}
